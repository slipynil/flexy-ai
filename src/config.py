"""Общие константы сервиса.

Сведены в одно место, чтобы бот и CLI-скрипты вели себя одинаково
(см. docs/adr/001-modularity-refactoring.md).
"""

# Промпт по умолчанию для генерации context2img
DEFAULT_PROMPT = "раздеть персонажа до гола, лицо и позу не менять"

# На сколько секунд аккаунт исключается из ротации после ошибки API
# (API временно блокирует аккаунт на 1-2 минуты)
ACCOUNT_COOLDOWN_SECONDS = 120

# --- Ожидание при деградации flexy-ai.com (хостинг отвечает медленно/сбросами) ---

# Таймаут на установку соединения (в requests передается кортежем (connect, read)):
# при «вне штатном» режиме хостинг может подвешивать коннект — обрываем раньше,
# не дожидаясь полного read-таймаута
HTTP_CONNECT_TIMEOUT = 10

# Общий бюджет на перебор аккаунтов и вход для одного запроса пользователя.
# Проверяется перед каждой новой попыткой: без потолка при медленном API бот
# последовательно жег по ~90 сек на аккаунт и пользователь ждал 3+ минуты,
# все равно получая ошибку. Успешно запущенная генерация не прерывается
# (опрос статуса ограничен отдельно — TASK_POLL_TIMEOUT_SECONDS)
GENERATION_DEADLINE_SECONDS = 180

# Сколько всего попыток входа на один аккаунт: вход/токен флапают
# (анти-бот хостинга отвечает success, но logged_in=False) — повторяем вход
# «с нуля» (свежий nonce), а не отправляем аккаунт в cooldown. Аналог приема
# из farm.py::verify_and_get_api_key
LOGIN_ATTEMPTS = 2

# Опрос статуса задачи генерации: интервал, максимальное ожидание результата
# (раньше while True без ограничения — поток мог крутиться вечно) и сколько
# подряд сетевых сбоев опроса терпим (транзиентные 5xx/сбросы при перегрузке)
TASK_POLL_INTERVAL_SECONDS = 2
TASK_POLL_TIMEOUT_SECONDS = 300
TASK_POLL_ERROR_ATTEMPTS = 3

# Ранний выход при системном отказе: флап токена (LoginFlapError — сервер
# принял логин, но не держит сессию) на N аккаунтах ПОДРЯД означает проблему
# серверную — остальные аккаунты жечь бессмысленно, сразу отвечаем отказом
SYSTEMIC_FAILURE_THRESHOLD = 2

# Сколько секунд после системного отказа новые запросы завершаются мгновенно,
# не трогая пул аккаунтов («предохранитель»). Больше ACCOUNT_COOLDOWN_SECONDS,
# чтобы к моменту повторного захода аккаунты уже вышли из cooldown
SERVICE_BREAKER_SECONDS = 300

# Сообщение пользователю при системном отказе (общее для бота и CLI)
SERVICE_UNAVAILABLE_MESSAGE = (
    "сервис flexy-ai.com временно недоступен (сбой на стороне хостинга), "
    "попробуйте позже"
)
